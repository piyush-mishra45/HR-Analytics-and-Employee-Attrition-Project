"""
Generate sql/insert_data.sql from the cleaned CSV.

Usage
-----
    python python/generate_sql_inserts.py
"""
from __future__ import annotations

import pandas as pd

import config as cfg

BATCH = 250  # rows per INSERT statement


def q(v) -> str:
    """Quote a value for SQL (numbers unquoted, strings escaped)."""
    if isinstance(v, str):
        return "'" + v.replace("\\", "\\\\").replace("'", "''") + "'"
    return str(int(v)) if float(v).is_integer() else str(v)


def insert_block(table: str, cols: list[str], rows: list[tuple]) -> list[str]:
    out = []
    for i in range(0, len(rows), BATCH):
        chunk = rows[i:i + BATCH]
        values = ",\n  ".join("(" + ", ".join(q(v) for v in r) + ")" for r in chunk)
        out.append(f"INSERT INTO {table} ({', '.join(cols)}) VALUES\n  {values};\n")
    return out


def build_sql(df: pd.DataFrame) -> str:
    dept = {n: i + 1 for i, n in enumerate(sorted(df["Department"].unique()))}
    role = {n: i + 1 for i, n in enumerate(sorted(df["JobRole"].unique()))}

    parts = [
        "-- =====================================================================\n"
        "-- Script 3 of 4 : load cleaned data (auto-generated by python/generate_sql_inserts.py)\n"
        f"-- Source: data/processed/hr_attrition_cleaned.csv  ({len(df)} employees)\n"
        "-- =====================================================================\n"
        "USE hr_analytics_db;\n\nSET FOREIGN_KEY_CHECKS = 0;\n"
        "TRUNCATE TABLE attrition_analysis;\nTRUNCATE TABLE employee_satisfaction;\n"
        "TRUNCATE TABLE employees;\nTRUNCATE TABLE job_roles;\nTRUNCATE TABLE departments;\n"
        "SET FOREIGN_KEY_CHECKS = 1;\n"
    ]
    parts += insert_block("departments", ["department_id", "department_name"],
                          [(i, n) for n, i in dept.items()])
    parts += insert_block("job_roles", ["job_role_id", "job_role_name"],
                          [(i, n) for n, i in role.items()])

    emp_cols = ["employee_number", "age", "gender", "marital_status", "education",
                "education_field", "department_id", "job_role_id", "job_level",
                "business_travel", "distance_from_home", "monthly_income",
                "percent_salary_hike", "performance_rating", "stock_option_level",
                "num_companies_worked", "total_working_years", "training_times_last_year",
                "years_at_company", "years_in_current_role", "years_since_last_promotion",
                "years_with_curr_manager", "overtime"]
    emp_rows = [(r.EmployeeNumber, r.Age, r.Gender, r.MaritalStatus, r.Education, r.EducationField,
                 dept[r.Department], role[r.JobRole], r.JobLevel, r.BusinessTravel,
                 r.DistanceFromHome, r.MonthlyIncome, r.PercentSalaryHike, r.PerformanceRating,
                 r.StockOptionLevel, r.NumCompaniesWorked, r.TotalWorkingYears,
                 r.TrainingTimesLastYear, r.YearsAtCompany, r.YearsInCurrentRole,
                 r.YearsSinceLastPromotion, r.YearsWithCurrManager, r.OverTime)
                for r in df.itertuples()]
    parts += insert_block("employees", emp_cols, emp_rows)

    parts += insert_block(
        "employee_satisfaction",
        ["employee_number", "environment_satisfaction", "job_satisfaction",
         "relationship_satisfaction", "work_life_balance", "job_involvement"],
        [(r.EmployeeNumber, r.EnvironmentSatisfaction, r.JobSatisfaction,
          r.RelationshipSatisfaction, r.WorkLifeBalance, r.JobInvolvement) for r in df.itertuples()])

    parts += insert_block(
        "attrition_analysis",
        ["employee_number", "attrition", "attrition_flag", "age_group", "salary_slab",
         "tenure_band", "promotion_gap"],
        [(r.EmployeeNumber, r.Attrition, r.AttritionFlag, r.AgeGroup, r.SalarySlab,
          r.TenureBand, r.PromotionGap) for r in df.itertuples()])

    parts.append("\n-- Quick sanity check\n"
                 "SELECT 'employees' AS tbl, COUNT(*) AS n FROM employees\n"
                 "UNION ALL SELECT 'employee_satisfaction', COUNT(*) FROM employee_satisfaction\n"
                 "UNION ALL SELECT 'attrition_analysis', COUNT(*) FROM attrition_analysis;\n")
    return "\n".join(parts)


def run() -> None:
    df = pd.read_csv(cfg.CLEAN_CSV)
    path = cfg.SQL_DIR / "insert_data.sql"
    path.write_text(build_sql(df), encoding="utf-8")
    print(f"Wrote {path}  ({path.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    run()
